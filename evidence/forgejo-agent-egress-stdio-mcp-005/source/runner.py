SANDBOX_WRAPPER = SCRIPT_DIR / "mission_012_sandboxed_test_adapter.py"
TASK_ADAPTER = SCRIPT_DIR / "mission_012_test_agent_adapter.py"
MCP_HOST = SCRIPT_DIR / "mission_012_egress_barrier_mcp_host.py"
EGRESS_HELPER = SCRIPT_DIR / "run_forgejo_agent_egress_live_e2e.py"
