def validate_direct_route_probe_diagnostics(value: object) -> None:
    """Require each adapter probe to fail at connect, before it sends a request."""
    expected_names = ["api", "web", "git_receive_pack"]
    if not isinstance(value, list) or len(value) != len(expected_names):
        raise RuntimeError("probe diagnostics must cover all direct routes")
    expected_keys = {"name", "phase", "error_category", "errno"}
    for expected_name, diagnostic in zip(expected_names, value):
        if (
            not isinstance(diagnostic, dict)
            or set(diagnostic) != expected_keys
            or diagnostic.get("name") != expected_name
        ):
            raise RuntimeError("probe diagnostics must identify all direct routes")
        if diagnostic.get("phase") != "connect":
            raise RuntimeError("direct route must be blocked at connect stage")
        code = diagnostic.get("errno")
        if (
            diagnostic.get("error_category") != "os_error"
            or type(code) is not int
            or code <= 0
        ):
            raise RuntimeError("connect-stage refusal must include a positive OS error number")


def run_task_at_barrier(
    *,
    state: Path,
    evidence: Path,
    workspace: Path,
    cargo_home: Path,
    task_home: Path,
    calls: Path,
    gate_token: str,
    gate_token_scope: str,
    credential_probe_path: str,
    branch: str,
    branch_before: str,
    cargo: Path,
    toolchain_bin: Path,
    wait_at_gate_barrier: bool = False,
    gate_callback: Callable[[], dict[str, Any]] | None = None,
    expected_fixed_source: str = FIXED_SOURCE,
    actionable_failure_markers: tuple[str, ...] = ACTIONABLE_FAILURE_MARKERS,
    branch_reader: Callable[[], str] | None = None,
    probe_owner: str = OWNER,
    probe_repository: str = REPOSITORY,
    probe_pull_number: int = PR_NUMBER,
    private_file_probes: list[tuple[str, Path]] | None = None,
) -> dict[str, Any]:
    if gate_callback is not None and not wait_at_gate_barrier:
        raise ValueError("a trusted gate callback requires the post-acceptance MCP barrier")
    ready = state / "mcp-barrier-ready"
    release = state / "mcp-barrier-release"
    mcp_config = state / "mcp-config.json"
    baseline_log = state / "acceptance-baseline.log"
    corrected_log = state / "acceptance-corrected.log"
    mcp_host_args = [
        "--workspace", str(workspace),
        "--calls-file", str(calls),
        "--barrier-ready", str(ready),
        "--barrier-release", str(release),
        "--cargo", str(cargo),
        "--toolchain-bin", str(toolchain_bin),
        "--cargo-home", str(cargo_home),
        "--home", str(task_home),
        "--baseline-log", str(baseline_log),
        "--corrected-log", str(corrected_log),
    ]
    if wait_at_gate_barrier:
        mcp_host_args.extend(["--barrier-on-context-call", "2"])
    forgejo_helpers.write_json(
        mcp_config,
        {
            "mcpServers": {
                "mission012": {
                    "command": "/usr/bin/python3",
                    "args": build_mcp_server_arguments(mcp_host_args),
                }
            }
        },
    )
    config_bytes = mcp_config.read_bytes()
    if gate_token.encode("ascii") in config_bytes:
        raise RuntimeError("trusted gate token was serialized into the MCP configuration")
    wrapper_command = [
        "/usr/bin/python3", str(SANDBOX_WRAPPER),
        "--mcp-config", str(mcp_config),
        "--forgejo-probe-port", str(PORT),
        "--credential-probe-path", credential_probe_path,
        "--probe-owner", probe_owner,
        "--probe-repository", probe_repository,
        "--probe-pull-number", str(probe_pull_number),
    ]
    for label, path in private_file_probes or []:
        wrapper_command.extend(("--probe-private-file", label, str(path)))
    if gate_token in " ".join(wrapper_command):
        raise RuntimeError("trusted gate token was serialized into the sandbox command")
    if wait_at_gate_barrier:
        wrapper_command.append("--wait-at-gate-barrier")
    wrapper_environment = {"PATH": "/usr/bin:/bin", "HOME": "/nonexistent", "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8"}
    if gate_token in wrapper_environment.values():
        raise RuntimeError("trusted gate token was serialized into the sandbox environment")
    output_path = evidence / "stdio-mcp-wrapper.stdout"
    error_path = evidence / "stdio-mcp-wrapper.stderr"
    gate_operation: dict[str, Any] | None = None
    sandbox_agent_before_gate: dict[str, Any] | None = None
    sandbox_agent_after_gate: dict[str, Any] | None = None
    with output_path.open("xb") as output, error_path.open("xb") as errors:
        process = subprocess.Popen(
            wrapper_command,
            cwd="/",
            env=wrapper_environment,
            stdin=subprocess.DEVNULL,
            stdout=output,
            stderr=errors,
            close_fds=True,
            start_new_session=True,
        )
        try:
            wait_for_gate_barrier(process, ready, calls)
            if not ready.is_file() or ready.is_symlink():
                raise RuntimeError("MCP gate barrier marker is not a regular file")
            if wait_at_gate_barrier:
                sandbox_agent_before_gate = observe_sandbox_agent_process_tree(process.pid)
            if branch_reader is None:
                branch_during_gate = egress.read_branch(forgejo_helpers.make_api(gate_token), branch)
            else:
                branch_during_gate = branch_reader()
            if branch_during_gate != branch_before:
                raise RuntimeError("trusted gate read observed an unexpected branch mutation")
            if wait_at_gate_barrier:
                sandbox_agent_after_gate = observe_sandbox_agent_process_tree(process.pid)
                identity_fields = (
                    "agent_host_pid",
                    "agent_start_time_ticks",
                    "agent_network_namespace",
                    "agent_pid_namespace",
                )
                if any(
                    sandbox_agent_before_gate.get(field)
                    != sandbox_agent_after_gate.get(field)
                    for field in identity_fields
                ):
                    raise RuntimeError("sandboxed agent process identity changed during the gate read")
            child_alive_during_gate_read = process.poll() is None
            if wait_at_gate_barrier:
                child_alive_during_gate_read = (
                    child_alive_during_gate_read
                    and sandbox_agent_before_gate is not None
                    and sandbox_agent_after_gate is not None
                    and sandbox_agent_before_gate.get("agent_alive") is True
                    and sandbox_agent_after_gate.get("agent_alive") is True
                )
            if not child_alive_during_gate_read:
                raise RuntimeError("sandboxed agent process exited before the trusted gate read completed")
            if gate_callback is not None:
                gate_operation = gate_callback()
                if not isinstance(gate_operation, dict):
                    raise RuntimeError("trusted gate callback did not return an evidence object")
                if process.poll() is not None:
                    raise RuntimeError("stdio-MCP wrapper exited while the trusted gate operation ran")
                if wait_at_gate_barrier:
                    sandbox_agent_after_gate = observe_sandbox_agent_process_tree(process.pid)
                    if any(
                        sandbox_agent_before_gate.get(field)
                        != sandbox_agent_after_gate.get(field)
                        for field in identity_fields
                    ):
                        raise RuntimeError("sandboxed agent process exited or changed during the gate operation")
                release_contents = b"trusted gate operation completed\n"
            else:
                release_contents = b"trusted gate read completed\n"
            write_exclusive(release, release_contents)
            status = process.wait(timeout=100)
            output.flush()
            errors.flush()
        except BaseException:
            if process.poll() is None:
                if not release.exists():
                    try:
                        write_exclusive(release, b"abort cleanup\n")
                    except FileExistsError:
                        pass
                try:
                    process.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    process.send_signal(signal.SIGTERM)
                    try:
                        process.wait(timeout=5)
                    except subprocess.TimeoutExpired:
                        process.kill()
                        process.wait(timeout=5)
            raise
    stdout = output_path.read_bytes()
    stderr = error_path.read_bytes()
    if len(stdout) > MAX_OUTPUT_BYTES or len(stderr) > MAX_OUTPUT_BYTES:
        raise RuntimeError("stdio-MCP wrapper output exceeded the local evidence bound")
    if status != 0:
        raise RuntimeError(f"stdio-MCP wrapper returned exit status {status}")
    lines = [line for line in stdout.splitlines() if line]
    if len(lines) != 1:
        raise RuntimeError("stdio-MCP wrapper did not return exactly one status record")
    event = json.loads(lines[0])
    if not isinstance(event, dict) or event.get("type") != "result" or event.get("subtype") != "success":
        raise RuntimeError("stdio-MCP task did not report a bounded success event")
    checks = event.get("sandbox_checks")
    if not isinstance(checks, dict):
        raise RuntimeError("stdio-MCP child did not return its sandbox observations")
    validate_direct_route_probe_diagnostics(checks.get("direct_forgejo_route_probe_errors"))
    if wait_at_gate_barrier:
        if sandbox_agent_before_gate is None or sandbox_agent_after_gate is None:
            raise RuntimeError("trusted runner did not observe the sandboxed agent at the gate barrier")
        if (
            checks.get("network_namespace")
            != sandbox_agent_after_gate.get("agent_network_namespace")
            or checks.get("pid_namespace")
            != sandbox_agent_after_gate.get("agent_pid_namespace")
            or event.get("host_network_namespace")
            != sandbox_agent_after_gate.get("host_network_namespace")
            or event.get("host_pid_namespace")
            != sandbox_agent_after_gate.get("host_pid_namespace")
        ):
            raise RuntimeError("sandbox agent self-report differs from the host process observation")
    if (
        checks.get("credential_visible") is not False
        or checks.get("network_connected") is not False
        or checks.get("direct_forgejo_routes_blocked") != ["api", "web", "git_receive_pack"]
        or checks.get("probe_target_port") != PORT
        or checks.get("open_fds") != [0, 1, 2]
        or checks.get("network_namespace") == event.get("host_network_namespace")
        or checks.get("pid_namespace") == event.get("host_pid_namespace")
        or checks.get("environment_keys") != ["HOME", "LANG", "LC_ALL", "PATH", "PWD", "PYTHONDONTWRITEBYTECODE"]
    ):
        raise RuntimeError("stdio-MCP task did not prove the expected isolated route refusals")
    written_source = (workspace / "src/lib.rs").read_text(encoding="utf-8")
    if written_source != expected_fixed_source:
        raise RuntimeError("stdio-MCP task did not apply the single authorized Rust fix")
    for source, name in (
        (baseline_log, "acceptance-baseline.log"),
        (corrected_log, "acceptance-corrected.log"),
    ):
        if not source.is_file() or source.is_symlink():
            raise RuntimeError("trusted MCP host did not preserve the actual Cargo output")
        shutil.copyfile(source, evidence / name)
        (evidence / name).chmod(0o600)
    baseline_output = baseline_log.read_text(encoding="utf-8", errors="replace")
    corrected_output = corrected_log.read_text(encoding="utf-8", errors="replace")
    if not all(marker in baseline_output for marker in actionable_failure_markers):
        raise RuntimeError("saved baseline Cargo output lacks the expected actionable assertion")
    if "test result: ok" not in corrected_output:
        raise RuntimeError("saved corrected Cargo output lacks a passing test result")
    methods = calls.read_text(encoding="utf-8").splitlines()
    expected_methods = expected_mcp_methods(wait_at_gate_barrier=wait_at_gate_barrier)
    if methods != expected_methods:
        raise RuntimeError("MCP host call log differs from the bounded task protocol")
    return {
        "adapter_event": event,
        "mcp_methods": methods,
        "mcp_barrier": {
            "reached_on": (
                "tools/call:mission_context after corrected acceptance"
                if wait_at_gate_barrier
                else "tools/call:mission_context before task execution"
            ),
            "child_process_alive_during_gate_read": child_alive_during_gate_read,
            "sandbox_agent_process_observation": (
                {
                    "before_gate": sandbox_agent_before_gate,
                    "after_gate": sandbox_agent_after_gate,
                    "observed_by": "trusted parent via /proc descendant tree",
                }
                if wait_at_gate_barrier
                else None
            ),
            "released_after_gate_read": release.read_text(encoding="utf-8").strip() == "trusted gate read completed",
            "released_after_gate_operation": release.read_text(encoding="utf-8").strip() == "trusted gate operation completed",
        },
        "trusted_gate_read": {
            "status": 200,
            "route": f"GET /api/v1/repos/{probe_owner}/{probe_repository}/branches/{branch}",
            "scope": gate_token_scope,
            "branch_sha_before": branch_before,
            "branch_sha_during_gate": branch_during_gate,
            "write_credential_passed_to_stdio_child": False,
            "write_credential_persisted_to_file": False,
            "credential_probe_target": "trusted runner's CLOEXEC memfd under its host /proc PID",
            "credential_probe_refused_inside_pid_namespace": checks.get("credential_visible") is False,
            "credential_not_serialized_to_mcp_config_command_or_environment": True,
            "credential_fd_inherited_by_stdio_child": False,
            "write_credential_created": True,
            "merge_route_called": gate_operation is not None,
        },
        "trusted_gate_operation": gate_operation,
        "source_changed_through_mcp": written_source == expected_fixed_source,
        "source_sha256": hashlib.sha256(written_source.encode()).hexdigest(),
        "task_acceptance": {
            "baseline_exit_code": 101,
            "baseline_actionable_failure": True,
            "corrected_exit_code": 0,
            "corrected_acceptance_pass": True,
            "verification": "actual cargo test --offline --locked in the trusted MCP host",
            "baseline_log_sha256": sha256(evidence / "acceptance-baseline.log"),
            "corrected_log_sha256": sha256(evidence / "acceptance-corrected.log"),
        },
        "sandbox_checks": checks,
        "wrapper_stderr_empty": stderr == b"",
    }


def run(args: argparse.Namespace) -> dict[str, Any]:
    binary_arg = Path(args.forgejo_binary)
    if binary_arg.is_symlink():
        raise RuntimeError("Forgejo binary must not be a symlink")
    binary = binary_arg.resolve(strict=True)
    if not binary.is_file():
        raise RuntimeError("Forgejo binary is unavailable")
    state = Path(args.state_dir)
    if not state.is_absolute() or state.parent != Path("/tmp") or state.exists():
        raise RuntimeError("state directory must be a new direct child of /tmp")
    evidence = Path(args.evidence_dir).resolve(strict=True)
    if {path.name for path in evidence.iterdir()} - {"red-live-composition.log"}:
        raise RuntimeError("evidence directory contains unexpected pre-existing files")
    if not SANDBOX_WRAPPER.is_file() or not TASK_ADAPTER.is_file() or not MCP_HOST.is_file():
        raise RuntimeError("local sandbox/MCP fixture sources are unavailable")
    with socket.socket() as listener:
        if listener.connect_ex(("127.0.0.1", PORT)) == 0:
            raise RuntimeError("the local Forgejo test port is already occupied")

    cargo = Path(subprocess.run(["rustup", "which", "cargo"], check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, timeout=5).stdout.strip()).resolve(strict=True)
    rustc = Path(subprocess.run(["rustup", "which", "rustc"], check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, timeout=5).stdout.strip()).resolve(strict=True)
    toolchain_bin = rustc.parent
    forgejo_version = egress.forgejo_version(binary)
    state.mkdir(mode=0o700)
    for name in ("data", "repositories", "log", "home", "tmp"):
        (state / name).mkdir(mode=0o700)
    forgejo_helpers.create_app_ini(state)
    server_log = (state / "log/server.log").open("xb")
    forgejo: subprocess.Popen[bytes] | None = None
    read_token = ""
    gate_token = ""
    gate_token_fd: int | None = None
    payload: dict[str, Any] | None = None
    stage = "start_forgejo"
    try:
        env = {
            "PATH": "/usr/bin:/bin",
            "HOME": str(state / "home"),
            "TMPDIR": str(state / "tmp"),
            "LANG": "C.UTF-8",
            "LC_ALL": "C.UTF-8",
        }
        forgejo = subprocess.Popen(
            [str(binary), "--work-path", str(state), "--config", str(state / "custom/conf/app.ini"), "web"],
            cwd=state,
            env=env,
            stdout=server_log,
            stderr=subprocess.STDOUT,
            close_fds=True,
            start_new_session=True,
        )
        forgejo_helpers.wait_for_health(forgejo)
        forgejo_helpers.assert_forgejo_listener(forgejo, PORT)
        stage = "provision_fixture"
        read_token, branch = egress.provision_repository(binary, state)
        read_token = ""
        gate_token_scope = "read:user,read:issue,read:repository,write:issue,write:repository"
        gate_token = egress.repository_token(
            binary,
            state,
            name="agent-egress-composed-gate-write",
            scopes=gate_token_scope,
        )
        gate_token_fd = os.memfd_create("forgejo-gate-write-credential", flags=os.MFD_CLOEXEC)
        gate_token_bytes = gate_token.encode("ascii")
        if os.write(gate_token_fd, gate_token_bytes) != len(gate_token_bytes):
            raise RuntimeError("trusted gate credential memfd write was incomplete")
        credential_probe_path = f"/proc/{os.getpid()}/fd/{gate_token_fd}"
        trusted_api = forgejo_helpers.make_api(gate_token)
        branch_before = egress.read_branch(trusted_api, branch)
        positives, routes = egress.host_route_statuses()

        workspace, cargo_home, task_home, calls = prepare_fixture(state)
        stage = "stdio_mcp_task_and_gate_barrier"
        task_result = run_task_at_barrier(
            state=state,
            evidence=evidence,
            workspace=workspace,
            cargo_home=cargo_home,
            task_home=task_home,
            calls=calls,
            gate_token=gate_token,
            gate_token_scope=gate_token_scope,
            credential_probe_path=credential_probe_path,
            branch=branch,
            branch_before=branch_before,
            cargo=cargo,
            toolchain_bin=toolchain_bin,
            wait_at_gate_barrier=True,
        )
        branch_after = egress.read_branch(trusted_api, branch)
        if branch_after != branch_before:
            raise RuntimeError("read-only task/gate composition changed the Forgejo branch")
        payload = {
            "schema_version": 1,
            "verdict": "passed",
            "forgejo": {
                "version": forgejo_version,
                "binary_sha256": egress.sha256(binary),
                "listener": f"127.0.0.1:{PORT}",
            },
            "host_route_controls": positives,
            "forgejo_routes": routes,
            "stdio_mcp_composition": task_result,
            "credential_boundary": {
                "write_credential_scope": gate_token_scope,
                "write_credential_held_in_runner_memory_and_cloexec_memfd": True,
                "write_credential_persisted_to_file": False,
                "write_credential_passed_to_stdio_child": False,
                "write_credential_fd_inherited_by_stdio_child": False,
                "write_credential_probe_refused_inside_child_pid_namespace": task_result["trusted_gate_read"]["credential_probe_refused_inside_pid_namespace"],
                "write_credential_not_serialized_to_mcp_config_command_or_environment": task_result["trusted_gate_read"]["credential_not_serialized_to_mcp_config_command_or_environment"],
            },
            "branch_sha_before": branch_before,
            "branch_sha_after": branch_after,
            "limitations": [
                "The MCP task process is the local-test-adapter, not an LLM or AgentOS runtime.",
                "The gate operation is a trusted read-only Forgejo API call; this run does not merge a PR.",
                "A local Forgejo token with write:repository scope stayed in the trusted runner and a CLOEXEC memfd; it was not persisted or passed to the task child. The gate made a read-only branch request, not a merge.",
                "The MCP fixture is local and allowlisted; this run does not establish multi-tenant isolation or kernel escape resistance.",
                "The host and disposable Forgejo process share the local user identity.",
            ],
        }
        source_dir = evidence / "source"
        source_dir.mkdir(mode=0o700)
        for src, name in (
            (Path(__file__).resolve(), "runner.py"),
            (SANDBOX_WRAPPER, "sandbox-wrapper.py"),
            (TASK_ADAPTER, "task-adapter.py"),
            (MCP_HOST, "mcp-host.py"),
            (EGRESS_HELPER, "egress-helper.py"),
            (FORGEJO_HELPER, "forgejo-helper.py"),
            (SANDBOX_TEST, "sandbox-tests.py"),
        ):
            shutil.copyfile(src, source_dir / name)
        for src, name in (
            (workspace / "Cargo.toml", "fixture-Cargo.toml"),
            (workspace / "Cargo.lock", "fixture-Cargo.lock"),
            (workspace / "tests/acceptance.rs", "fixture-acceptance.rs"),
            (workspace / "src/lib.rs", "fixture-source-final.rs"),
        ):
            shutil.copyfile(src, source_dir / name)
        write_exclusive(source_dir / "fixture-source-initial.rs", INITIAL_SOURCE.encode(), 0o600)
        egress.write_json(
            evidence / "provenance.json",
            {
                "head_commit": subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, timeout=5).stdout.strip(),
                "runner_sha256": sha256(Path(__file__).resolve()),
                "sandbox_wrapper_sha256": sha256(SANDBOX_WRAPPER),
                "task_adapter_sha256": sha256(TASK_ADAPTER),
                "mcp_host_sha256": sha256(MCP_HOST),
                "egress_helper_sha256": sha256(EGRESS_HELPER),
                "forgejo_helper_sha256": sha256(FORGEJO_HELPER),
                "sandbox_test_sha256": sha256(SANDBOX_TEST),
                "forgejo_binary_sha256": egress.sha256(binary),
                "cargo": str(cargo),
                "rustc": str(rustc),
                "cargo_version": subprocess.run([str(cargo), "--version"], check=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=5, env={"PATH": f"{toolchain_bin}:/usr/bin:/bin", "HOME": "/nonexistent"}).stdout.strip(),
                "bubblewrap_version": subprocess.run(["/usr/bin/bwrap", "--version"], check=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=5).stdout.strip(),
                "python_version": sys.version.split()[0],
                "kernel": subprocess.run(["uname", "-srmo"], check=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=5).stdout.strip(),
                "fixture_hashes": {
                    name: sha256(source_dir / name)
                    for name in (
                        "fixture-Cargo.toml", "fixture-Cargo.lock", "fixture-acceptance.rs",
                        "fixture-source-initial.rs", "fixture-source-final.rs",
                    )
                },
                "sandbox_boundary": "actual --stdio-mcp task child launched by Bubblewrap --unshare-net/--unshare-pid; trusted gate read held outside child namespace",
            },
        )
        stage = "result_validation"
    except BaseException as error:
        try:
            egress.write_json(evidence / "failure.json", {"stage": stage, "error_type": type(error).__name__})
        except FileExistsError:
            pass
        raise
    finally:
        read_token = ""
        gate_token = ""
        if gate_token_fd is not None:
            os.close(gate_token_fd)
        cleanup = egress.stop_forgejo(forgejo)
        server_log.close()
        if payload is not None:
            payload["cleanup"] = cleanup
            egress.write_json(evidence / "result.json", payload)
    if payload is None:
        raise RuntimeError("no composed egress result was produced")
    if payload["cleanup"] != {"forgejo_exited": True, "returncode": 0, "listener_absent": True}:
        raise RuntimeError("disposable Forgejo cleanup was not confirmed")
    return payload


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--forgejo-binary", required=True)
    parser.add_argument("--state-dir", required=True)
    parser.add_argument("--evidence-dir", required=True)
    args = parser.parse_args()
    try:
        result = run(args)
    except Exception as error:
        print(json.dumps({"verdict": "failed", "error_type": type(error).__name__}, sort_keys=True))
        return 1
    print(json.dumps({
        "verdict": result["verdict"],
        "forgejo": result["forgejo"],
        "mcp_task": result["stdio_mcp_composition"]["task_acceptance"],
        "trusted_gate_read": result["stdio_mcp_composition"]["trusted_gate_read"],
        "cleanup": result["cleanup"],
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
