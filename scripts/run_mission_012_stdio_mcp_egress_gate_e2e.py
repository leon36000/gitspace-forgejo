def build_mcp_server_arguments(host_arguments: list[str]) -> list[str]:
    """Build the trusted supervisor command consumed by the sandbox wrapper."""
    if str(MCP_HOST) in host_arguments:
        raise ValueError("MCP host entrypoint must not be repeated in its options")
    if any(
        not isinstance(argument, str) or "\x00" in argument or argument == "--"
        for argument in host_arguments
    ):
        raise ValueError("MCP host arguments must be strings without a host separator")
    return [str(MCP_SUPERVISOR), "--", "/usr/bin/python3", str(MCP_HOST), *host_arguments]

