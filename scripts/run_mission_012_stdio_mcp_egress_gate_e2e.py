def wait_for_gate_barrier(process: subprocess.Popen[bytes], ready: Path, calls: Path) -> None:
    deadline = time.monotonic() + 30
    while time.monotonic() < deadline:
        if ready.exists():
            methods = calls.read_text(encoding="utf-8").splitlines()
            if not methods or methods[-1] != "tools/call:mission_context":
                raise RuntimeError("MCP host raised the gate barrier outside mission_context")
            if process.poll() is not None:
                raise RuntimeError("stdio-MCP task process exited before the trusted gate request")
            return
        if process.poll() is not None:
            raise RuntimeError("stdio-MCP task process exited before reaching the MCP barrier")
        time.sleep(0.02)
    raise RuntimeError("stdio-MCP task did not reach its bounded MCP barrier")


def _read_process_binding(pid: int) -> dict[str, int | str]:
    process_dir = Path("/proc") / str(pid)
    stat_path = process_dir / "stat"
    try:
        first_stat = stat_path.read_text(encoding="ascii")
        close_paren = first_stat.rfind(")")
        if close_paren < 0:
            raise ValueError("malformed process stat")
        fields = first_stat[close_paren + 1 :].split()
        parent_pid = int(fields[1])
        start_time_ticks = int(fields[19])
        network_namespace = os.readlink(process_dir / "ns/net")
        pid_namespace = os.readlink(process_dir / "ns/pid")
        second_network_namespace = os.readlink(process_dir / "ns/net")
        second_pid_namespace = os.readlink(process_dir / "ns/pid")
        second_stat = stat_path.read_text(encoding="ascii")
        second_close_paren = second_stat.rfind(")")
        if second_close_paren < 0:
            raise ValueError("malformed process stat")
        second_fields = second_stat[second_close_paren + 1 :].split()
        second_parent_pid = int(second_fields[1])
        second_start_time_ticks = int(second_fields[19])
    except (OSError, ValueError, IndexError) as error:
        raise RuntimeError(
            f"cannot read a stable process binding for pid {pid} ({type(error).__name__})"
        ) from error
    if (
        start_time_ticks <= 0
        or second_start_time_ticks != start_time_ticks
        or second_parent_pid != parent_pid
        or network_namespace != second_network_namespace
        or pid_namespace != second_pid_namespace
        or re.fullmatch(r"pid:\[[1-9][0-9]*\]", pid_namespace) is None
        or re.fullmatch(r"net:\[[1-9][0-9]*\]", network_namespace) is None
    ):
        raise RuntimeError(f"process binding changed while observing pid {pid}")
    return {
        "pid": pid,
        "parent_pid": parent_pid,
        "start_time_ticks": start_time_ticks,
        "network_namespace": network_namespace,
        "pid_namespace": pid_namespace,
    }


def _process_children(pid: int) -> set[int]:
    tasks_path = Path("/proc") / str(pid) / "task"
    try:
        task_ids = [entry.name for entry in tasks_path.iterdir()]
    except OSError as error:
        raise RuntimeError(f"cannot enumerate process tasks for pid {pid}") from error
    children: set[int] = set()
    for task_id in task_ids:
        children_path = tasks_path / task_id / "children"
        try:
            raw = children_path.read_text(encoding="ascii")
        except FileNotFoundError:
            continue
        except OSError as error:
            raise RuntimeError(f"cannot enumerate children of pid {pid}") from error
        for value in raw.split():
            if not value.isascii() or not value.isdecimal():
                raise RuntimeError(f"invalid child pid reported for process {pid}")
            children.add(int(value))
    return children


def observe_sandbox_agent_process_tree(wrapper_pid: int) -> dict[str, Any]:
    """Independently find the live adapter child and its host-observed namespaces."""
    if isinstance(wrapper_pid, bool) or not isinstance(wrapper_pid, int) or wrapper_pid <= 0:
        raise RuntimeError("sandbox process observation requires a positive wrapper PID")

    host_network_namespace = os.readlink("/proc/self/ns/net")
    host_pid_namespace = os.readlink("/proc/self/ns/pid")
    root = _read_process_binding(wrapper_pid)
    if (
        root["network_namespace"] != host_network_namespace
        or root["pid_namespace"] != host_pid_namespace
    ):
        raise RuntimeError("trusted sandbox wrapper unexpectedly left the host namespaces")

    queue = [wrapper_pid]
    seen = {wrapper_pid}
    agent_bindings: list[dict[str, int | str]] = []
    while queue:
        parent_pid = queue.pop()
        for child_pid in _process_children(parent_pid):
            if child_pid in seen:
                continue
            if len(seen) >= 256:
                raise RuntimeError("sandbox wrapper process tree exceeds the observation bound")
            try:
                binding = _read_process_binding(child_pid)
            except RuntimeError as error:
                if not (Path("/proc") / str(child_pid)).exists():
                    continue
                raise error
            if binding["parent_pid"] != parent_pid:
                raise RuntimeError("sandbox process tree changed during host observation")
            seen.add(child_pid)
            queue.append(child_pid)

            if (
                binding["network_namespace"] == host_network_namespace
                and binding["pid_namespace"] == host_pid_namespace
            ):
                continue
            try:
                command = (Path("/proc") / str(child_pid) / "cmdline").read_bytes()
            except OSError as error:
                raise RuntimeError("cannot read sandbox descendant command identity") from error
            if len(command) > 64 * 1024:
                raise RuntimeError("sandbox descendant command identity exceeds its bound")
            argv = command.rstrip(b"\0").split(b"\0")
            if (
                len(argv) >= 2
                and argv[0] == b"/usr/bin/python3"
                and argv[1] == b"/opt/mission_012_test_agent_adapter.py"
            ):
                agent_bindings.append(binding)

    if len(agent_bindings) != 1:
        raise RuntimeError(
            "supervisor could not find exactly one live sandboxed agent descendant"
        )
    agent = agent_bindings[0]
    if (
        agent["network_namespace"] == host_network_namespace
        or agent["pid_namespace"] == host_pid_namespace
    ):
        raise RuntimeError("sandboxed agent descendant is still in a host namespace")
    return {
        "agent_alive": True,
        "agent_entrypoint": "mission_012_test_agent_adapter.py",
        "agent_host_pid": agent["pid"],
        "agent_start_time_ticks": agent["start_time_ticks"],
        "agent_network_namespace": agent["network_namespace"],
        "agent_pid_namespace": agent["pid_namespace"],
        "host_network_namespace": host_network_namespace,
        "host_pid_namespace": host_pid_namespace,
        "observed_by_parent_procfs": True,
    }


