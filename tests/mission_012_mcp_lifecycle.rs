/// Run the system Git with no inherited configuration and fixed identities.
fn git(repository: &Path, args: &[&str], date: &str) -> Vec<u8> {
    let output = Command::new("/usr/bin/git")
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", "/nonexistent")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_TERMINAL_PROMPT", "0")
        .env("GIT_AUTHOR_NAME", "Mission Fixture")
        .env("GIT_AUTHOR_EMAIL", "fixture@example.invalid")
        .env("GIT_AUTHOR_DATE", date)
        .env("GIT_COMMITTER_NAME", "Mission Fixture")
        .env("GIT_COMMITTER_EMAIL", "fixture@example.invalid")
        .env("GIT_COMMITTER_DATE", date)
        .arg("-C")
        .arg(repository)
        .args(args)
        .stdin(Stdio::null())
        .output()
        .expect("run the local Git executable");
    assert!(
        output.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    output.stdout
}

fn git_text(repository: &Path, args: &[&str]) -> String {
    String::from_utf8(git(repository, args, "2026-10-22T00:00:00Z"))
        .expect("Git output is UTF-8")
        .trim()
        .to_owned()
}

/// Initialize `repository` on `main` if needed and commit every file in it.
fn commit_all(repository: &Path, date: &str) -> String {
    if !repository.join(".git").exists() {
        git(repository, &["init", "-q", "-b", "main"], date);
    }
    git(repository, &["add", "-A"], date);
    git(
        repository,
        &["commit", "-q", "-m", "synthetic protected base"],
        date,
    );
    git_text(repository, &["rev-parse", "HEAD"])
}

/// Deterministic loopback-free admission source backed by a local Git
/// repository. It models the Forgejo reads that admission performs: an open
/// issue, a protected `main` head, and requirement files at that exact commit.
struct SyntheticAdmissionSource {
    repository: PathBuf,
    work_item_content: Option<UntrustedWorkItemContentV1>,
}

impl MissionAdmissionSourceV1 for SyntheticAdmissionSource {
    fn read_issue(
        &self,
        scope: &BaseBranchScope,
        issue_number: u64,
    ) -> Result<IssueSnapshotV1, SourceFailureV1> {
        Ok(IssueSnapshotV1 {
            number: issue_number,
            html_url: format!(
                "{}/{}/{}/issues/{issue_number}",
                scope.origin(),
                scope.owner(),
                scope.repository()
            ),
            state: MissionIssueStateV1::Open,
            work_item_content: self.work_item_content.clone(),
        })
    }

    fn read_protected_branch_head(
        &self,
        scope: &BaseBranchScope,
    ) -> Result<ProtectedBranchHeadV1, SourceFailureV1> {
        Ok(ProtectedBranchHeadV1 {
            branch: scope.branch().to_owned(),
            commit: git_text(
                &self.repository,
                &["rev-parse", &format!("refs/heads/{}", scope.branch())],
            ),
            protected: true,
        })
    }

    fn read_requirement_file_at(
        &self,
        _scope: &BaseBranchScope,
        commit: &str,
        path: &str,
    ) -> Result<Vec<u8>, SourceFailureV1> {
        Ok(git(
            &self.repository,
            &["show", &format!("{commit}:{path}")],
            "2026-10-22T00:00:00Z",
        ))
    }

    fn list_requirement_paths_at(
        &self,
        _scope: &BaseBranchScope,
        commit: &str,
    ) -> Result<Vec<String>, SourceFailureV1> {
        Ok(git_text(
            &self.repository,
            &["ls-tree", "--name-only", commit, "requirements/"],
        )
        .lines()
        .map(str::to_owned)
        .collect())
    }
}

