        serde_json::from_str(&initialization_response).expect("initialization response is JSON");
    assert_eq!(initialization["id"], 1);

    let host_deadline = Instant::now() + Duration::from_secs(5);
    let host_pid = loop {
        if let Some(pid) = linux_direct_children(supervisor_pid).first().copied() {
            break pid;
        }
        assert!(
            Instant::now() < host_deadline,
            "supervisor did not start the MCP host"
        );
        thread::sleep(Duration::from_millis(2));
    };
    process_groups.0.push(host_pid as i32);
