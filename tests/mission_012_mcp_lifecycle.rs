struct TempDirectory(PathBuf);

impl TempDirectory {
    fn new() -> Self {
        let root = std::env::temp_dir().join(format!(
            "mission-012-mcp-lifecycle-{}-{}",
            std::process::id(),
            NEXT_TEMP_ID.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir(&root).expect("create private lifecycle test directory");
        fs::set_permissions(&root, fs::Permissions::from_mode(0o700))
            .expect("make lifecycle directory private");
        for snapshot in ["base", "candidate", TRUSTED_REPOSITORY] {
            write_base_snapshot(&root.join(snapshot));
        }
        commit_all(&root.join(TRUSTED_REPOSITORY), "2026-10-22T00:00:00Z");
        fs::create_dir(root.join("target")).expect("create fresh verifier target");
        Self(root)
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDirectory {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

