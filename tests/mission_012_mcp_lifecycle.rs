fn linux_process_state(pid: u32) -> Option<char> {
    let stat = fs::read_to_string(format!("/proc/{pid}/stat")).ok()?;
    let (_, fields) = stat.rsplit_once(')')?;
    fields.trim_start().chars().next()
}

fn linux_direct_children(pid: u32) -> Vec<u32> {
    fs::read_to_string(format!("/proc/{pid}/task/{pid}/children"))
        .unwrap_or_default()
        .split_whitespace()
        .filter_map(|child| child.parse().ok())
        .collect()
}

fn linux_descendants(pid: u32) -> Vec<u32> {
    let mut pending = linux_direct_children(pid);
    let mut descendants = Vec::new();
    while let Some(child) = pending.pop() {
        if descendants.contains(&child) {
            continue;
        }
        descendants.push(child);
        pending.extend(linux_direct_children(child));
    }
    descendants
}

fn linux_cgroup_path(pid: u32) -> Option<String> {
    fs::read_to_string(format!("/proc/{pid}/cgroup"))
        .ok()?
        .lines()
        .find_map(|line| line.strip_prefix("0::").map(str::to_owned))
}

fn linux_verifier_scope_cgroup(host_pid: u32) -> Option<String> {
    linux_descendants(host_pid).into_iter().find_map(|pid| {
        let path = linux_cgroup_path(pid)?;
        let unit = path.rsplit('/').next()?;
        (unit.starts_with("run-") && unit.ends_with(".scope")).then_some(path)
    })
}

fn linux_pids_in_cgroup(cgroup_path: &str) -> Vec<u32> {
    let Ok(processes) = fs::read_dir("/proc") else {
        return Vec::new();
    };
    processes
        .filter_map(Result::ok)
        .filter_map(|entry| entry.file_name().to_string_lossy().parse::<u32>().ok())
        .filter(|pid| {
            linux_cgroup_path(*pid).is_some_and(|path| {
                path == cgroup_path || path.starts_with(&format!("{cgroup_path}/"))
            })
        })
        .collect()
}

fn live_process_in_cgroup(
    cgroup_path: &str,
    process_state: Option<char>,
    process_cgroup: Option<&str>,
) -> bool {
    let Some(process_state) = process_state else {
        return false;
    };
    if matches!(process_state, 'Z' | 'X') {
        return false;
    }
    process_cgroup
        .is_some_and(|path| path == cgroup_path || path.starts_with(&format!("{cgroup_path}/")))
}

fn linux_live_pids_in_cgroup(cgroup_path: &str) -> Vec<u32> {
    linux_pids_in_cgroup(cgroup_path)
        .into_iter()
        .filter(|pid| {
            let state = linux_process_state(*pid);
            let process_cgroup = linux_cgroup_path(*pid);
            live_process_in_cgroup(cgroup_path, state, process_cgroup.as_deref())
        })
        .collect()
}

