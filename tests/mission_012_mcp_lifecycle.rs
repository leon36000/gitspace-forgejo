fn mcp_host_refuses_tool_calls_after_the_claimed_lease_expires() {
    let temp = TempDirectory::new();
    let root = temp.path();
    let execution = claim_execution(root);
    let config_path = write_host_config(root, &execution, 100);
    let mut child = Command::new(env!("CARGO_BIN_EXE_mission-012-mcp-host"))
        .arg("--config")
        .arg(&config_path)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("start the claim-bound stdio MCP host");
    let mut input = child.stdin.take().expect("MCP stdin is piped");
    let mut output = std::io::BufReader::new(child.stdout.take().expect("MCP stdout is piped"));
    let mut stderr = child.stderr.take().expect("MCP stderr is piped");
    let stderr_reader = thread::spawn(move || {
        let mut text = String::new();
        let _ = stderr.read_to_string(&mut text);
        text
    });
    input
        .write_all(
            concat!(
                "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"initialize\",\"params\":{\"protocolVersion\":\"2025-06-18\"}}\n",
                "{\"jsonrpc\":\"2.0\",\"method\":\"notifications/initialized\"}\n"
            )
            .as_bytes(),
        )
        .expect("initialize MCP before the lease expires");
    input.flush().expect("flush MCP initialization");
    let mut initialization_response = String::new();
    output
        .read_line(&mut initialization_response)
        .expect("read MCP initialization response");
    let initialization: Value =
        serde_json::from_str(&initialization_response).expect("initialization response is JSON");
    assert_eq!(initialization["id"], 1);
    assert_eq!(initialization["result"]["protocolVersion"], "2025-06-18");
    // Well past the 100 ms TTL even if the host starts late.
    thread::sleep(Duration::from_millis(600));
    input
        .write_all(
            concat!(
                "{\"jsonrpc\":\"2.0\",\"id\":2,\"method\":\"tools/call\",\"params\":{\"name\":\"workspace_read_text\",\"arguments\":{\"path\":\"src/lib.rs\"}}}\n",
                "{\"jsonrpc\":\"2.0\",\"method\":\"notifications/exit\"}\n"
            )
            .as_bytes(),
        )
        .expect("attempt a read after lease expiry");
    drop(input);
    let mut response_lines = vec![initialization_response];
    let mut line = String::new();
    while output.read_line(&mut line).expect("read MCP tool response") > 0 {
        response_lines.push(std::mem::take(&mut line));
    }
    drop(output);
    let status = child.wait().expect("wait for MCP host");
    let stderr = stderr_reader.join().expect("collect MCP stderr");
    assert_eq!(status.code(), Some(2));
    let responses: Vec<Value> = response_lines
        .iter()
        .map(|line| serde_json::from_str(line).expect("response is JSON"))
        .collect();
    let diagnostic_receipts = fs::read_to_string(root.join("receipt.jsonl"))
        .unwrap_or_else(|error| format!("receipt log unavailable: {error}"));
    assert_eq!(
        tool_text(response_for(&responses, 2))["code"],
        "execution_lease_expired",
        "responses={responses:?}; stderr={stderr}; receipts={diagnostic_receipts}"
    );
    let receipt_log = fs::read_to_string(root.join("receipt.jsonl"))
        .expect("host records the expired lease refusal");
    let finalization: Value = receipt_log
        .lines()
        .map(|line| serde_json::from_str(line).expect("receipt line is JSON"))
        .find(|record: &Value| record["event"] == "host_finalization")
        .expect("host writes finalization receipt");
    assert_eq!(finalization["outcome"], "refused");
    assert_eq!(finalization["error"]["code"], "execution_lease_expired");
    assert_eq!(
        finalization["execution_binding"]["mission_id"],
        execution.request.mission_id
    );
}

