    assert_eq!(unsafe { kill(supervisor_pid as i32, SIGTERM) }, 0);
    let wait_deadline = Instant::now() + Duration::from_secs(20);
    let status = loop {
        if let Some(status) = child.try_wait().expect("poll supervisor cancellation") {
            break status;
        }
        assert!(
            Instant::now() < wait_deadline,
            "supervisor did not honor its bounded cancellation deadline"
        );
        thread::sleep(Duration::from_millis(20));
    };
    drop(input);
    let mut remaining_output = Vec::new();
    output
        .read_to_end(&mut remaining_output)
        .expect("drain supervisor stdout after cancellation");
    let stderr = stderr_reader.join().expect("collect supervisor stderr");
