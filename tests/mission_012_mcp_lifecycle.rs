struct ProcessGroupsCleanup(Vec<i32>);

impl Drop for ProcessGroupsCleanup {
    fn drop(&mut self) {
        for process_group in &self.0 {
            unsafe {
                let _ = kill(-process_group, SIGCONT);
                let _ = kill(-process_group, SIGKILL);
            }
        }
    }
}

struct VerifierCgroupCleanup(String);

impl Drop for VerifierCgroupCleanup {
    fn drop(&mut self) {
        for pid in linux_pids_in_cgroup(&self.0) {
            unsafe {
                let _ = kill(pid as i32, SIGCONT);
                let _ = kill(pid as i32, SIGKILL);
            }
        }
    }
}

