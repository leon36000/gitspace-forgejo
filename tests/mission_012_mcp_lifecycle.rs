#[test]
#[ignore = "run only through the local bwrap process-isolation harness"]
fn webhook_source_handoff_process_rejects_missing_and_stale_receipts_before_mcp() {
    let temp = TempDirectory::new();
    let root = temp.path();
    let execution = claim_execution(root);
    let (config_path, inbox_path, source_path) = write_webhook_source_host_config(root, &execution);
    let saved_source_path = root.join("admission-source-saved.json");

    let original_config = fs::read(&config_path).expect("save the valid host configuration");
    rewrite_host_config(&config_path, |config| {
        config["trusted_webhook_attestation_public_keys_hex"] = json!([]);
        config["webhook_inbox_file"] = json!(root.join("inbox-must-not-be-read.jsonl"));
    });
    let missing_trust = run_host(&config_path, "");
    assert_eq!(missing_trust.status.code(), Some(65));
    assert!(
        String::from_utf8_lossy(&missing_trust.stderr)
            .contains("host_journal_attestation_policy_missing")
    );
    assert!(!root.join("receipt.jsonl").exists());

    rewrite_host_config(&config_path, |config| {
        config["trusted_webhook_attestation_public_keys_hex"] = json!([hex::encode(
            SigningKey::from_bytes(&[18; 32]).verifying_key().as_bytes()
        )]);
        config["webhook_inbox_file"] = json!(inbox_path);
    });
    let untrusted_key = run_host(&config_path, "");
    assert_eq!(untrusted_key.status.code(), Some(65));
    let untrusted_key_stderr = String::from_utf8_lossy(&untrusted_key.stderr);
    assert!(
        untrusted_key_stderr.contains("host_journal_attestation_untrusted_key"),
        "unexpected untrusted-key refusal: {untrusted_key_stderr}"
    );
    assert!(!root.join("receipt.jsonl").exists());
    fs::write(&config_path, &original_config).expect("restore the valid host configuration");

    fs::rename(&source_path, &saved_source_path)
        .expect("hide the source receipt for the missing-receipt refusal");
    let missing = run_host(&config_path, "");
    assert_eq!(missing.status.code(), Some(65));
    assert!(String::from_utf8_lossy(&missing.stderr).contains("host_admission_source_unavailable"));
    assert!(!root.join("receipt.jsonl").exists());
    fs::rename(&saved_source_path, &source_path).expect("restore the source receipt");

    let source_bytes = fs::read(&source_path).expect("save the original source receipt bytes");
    write_tampered_source_receipt(&source_path);
    let stale = run_host(&config_path, "");
    assert_eq!(stale.status.code(), Some(65));
    assert!(String::from_utf8_lossy(&stale.stderr).contains("host_admission_source_mismatch"));
    assert!(!root.join("receipt.jsonl").exists());

    fs::write(&source_path, source_bytes).expect("restore the original source receipt");
    let initialize = concat!(
        "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"initialize\",",
        "\"params\":{\"protocolVersion\":\"2025-06-18\"}}\n"
    );
    let accepted = run_host(&config_path, initialize);
    // EOF invokes finalization, which correctly refuses because no acceptance
    // run was performed. Receipt creation and MCP initialization prove that
    // the valid webhook source was accepted before execution began.
    assert_eq!(accepted.status.code(), Some(2));
    let response: Value =
        serde_json::from_slice(accepted.stdout.split(|byte| *byte == b'\n').next().unwrap())
            .expect("valid-source host returned an MCP initialization response");
    assert_eq!(response["id"], 1);
    assert_eq!(response["result"]["protocolVersion"], "2025-06-18");
    let records = receipt_records(&root.join("receipt.jsonl"));
    assert_eq!(records.first().unwrap()["event"], "execution_started");
    assert_eq!(records.last().unwrap()["event"], "host_finalization");
    assert_eq!(records.last().unwrap()["outcome"], "refused");
    assert_eq!(
        records.last().unwrap()["error"]["code"],
        "baseline_not_verified"
    );
}
