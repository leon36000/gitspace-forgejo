/// Send a potentially large request without letting a blocked stdin write
/// bypass the process deadline. A child that exits before consuming stdin may
/// close the pipe; that BrokenPipe is checked by the caller's response and
/// state assertions.
fn run_child_with_input_deadline(
    mut child: Child,
    input: String,
    limit: Duration,
) -> Result<std::process::Output, std::process::Output> {
    let deadline = Instant::now() + limit;
    let mut stdin = child.stdin.take().expect("child stdin is piped");
    let writer = thread::spawn(move || stdin.write_all(input.as_bytes()));
    let result = wait_until_deadline(child, deadline);
    if let Err(error) = writer.join().expect("join the child stdin writer") {
        assert_eq!(
            error.kind(),
            std::io::ErrorKind::BrokenPipe,
            "send the child input: {error}"
        );
    }
    result
}

/// Wait for the child, killing it and collecting its output at the deadline.
/// Keeping the timeout result lets callers join their I/O workers before they
/// fail, so a blocked stdin writer cannot outlive the test.
fn wait_until_deadline(
    child: Child,
    deadline: Instant,
) -> Result<std::process::Output, std::process::Output> {
    // Callers create a fresh process group so a timeout also ends descendants
    // that could retain stdin/stdout/stderr descriptors.
    let process_group = child.id() as i32;
    let (send_output, receive_output) = mpsc::sync_channel(1);
    let waiter = thread::spawn(move || {
        let output = child
            .wait_with_output()
            .expect("collect MCP host output while waiting");
        let finished_at = Instant::now();
        let _ = send_output.send((output, finished_at));
    });
    let remaining = deadline.saturating_duration_since(Instant::now());
    match receive_output.recv_timeout(remaining) {
        Ok((output, finished_at)) => {
            waiter.join().expect("join MCP host waiter");
            if finished_at <= deadline {
                Ok(output)
            } else {
                Err(output)
            }
        }
        Err(RecvTimeoutError::Timeout) => match receive_output.try_recv() {
            Ok((output, finished_at)) => {
                waiter.join().expect("join MCP host waiter at deadline");
                if finished_at <= deadline {
                    Ok(output)
                } else {
                    Err(output)
                }
            }
            Err(TryRecvError::Empty) => {
                let result = unsafe { kill(-process_group, SIGKILL) };
                if result != 0 {
                    let error = std::io::Error::last_os_error();
                    assert_eq!(
                        error.kind(),
                        std::io::ErrorKind::NotFound,
                        "kill timed-out MCP process group: {error}"
                    );
                }
                let (output, finished_at) = receive_output
                    .recv()
                    .expect("collect MCP host output after process-group kill");
                waiter
                    .join()
                    .expect("join MCP host waiter after process-group kill");
                if finished_at <= deadline {
                    Ok(output)
                } else {
                    Err(output)
                }
            }
            Err(TryRecvError::Disconnected) => {
                panic!("MCP host waiter exited without returning output")
            }
        },
        Err(RecvTimeoutError::Disconnected) => {
            panic!("MCP host waiter exited without returning output")
        }
    }
}

/// Wait for the host, killing it and failing if it does not exit in time, so
/// a host that spins on a broken stream fails the test instead of hanging it.
fn wait_with_deadline(child: Child, limit: Duration) -> std::process::Output {
    match wait_until_deadline(child, Instant::now() + limit) {
        Ok(output) => output,
        Err(output) => panic!("MCP host did not exit within {limit:?}: {}", output.status),
    }
}

